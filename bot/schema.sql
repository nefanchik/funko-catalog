CREATE TABLE IF NOT EXISTS subs (
  user_id INTEGER PRIMARY KEY,
  name TEXT,
  all_new INTEGER DEFAULT 0,
  cats TEXT DEFAULT '[]',
  tags TEXT DEFAULT '[]',
  words TEXT DEFAULT '[]',
  updated INTEGER
);
CREATE TABLE IF NOT EXISTS seen (id INTEGER PRIMARY KEY);
CREATE TABLE IF NOT EXISTS outbox (n INTEGER PRIMARY KEY AUTOINCREMENT, user_id INTEGER, body TEXT);
